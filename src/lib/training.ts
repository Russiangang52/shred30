export interface Exercise {
  name: string;
  sets: string; // подходы × повторы
  rest: string; // отдых
  note?: string;
}

export interface GymTraining {
  kind: "gym";
  day: string; // Пн, Вт...
  title: string;
  focus: string;
  duration: string;
  kcalBurn: string;
  exercises: Exercise[];
  finisher: string;
}

export interface HockeyDay {
  kind: "hockey";
  day: string;
  title: string;
  focus: string;
  duration: string;
  kcalBurn: string;
  bullets: string[];
}

export interface RestDay {
  kind: "rest";
  day: string;
  title: string;
  focus: string;
  bullets: string[];
}

export type DayPlan = GymTraining | HockeyDay | RestDay;

